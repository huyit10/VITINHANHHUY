window.VTH_Catalog = {
    PER_PAGE: 12,

    formatPrice: function (n) {
        return n.toString().replace(/\B(?=(\d{3})+(?!\d))/g, '.') + ' ₫';
    },

    discountPct: function (price, originalPrice) {
        if (!originalPrice || originalPrice <= price) return 0;
        return Math.round((1 - price / originalPrice) * 100);
    },

    normalize: function (s) {
        return (s || '').toLowerCase()
            .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
            .replace(/[–—]/g, '-')
            .replace(/\s+/g, ' ')
            .trim();
    },

    resolveCategoryKeys: function (query) {
        var q = this.normalize(query);
        if (!q) return null;

        var bestKeys = null;
        var bestScore = 0;

        window.VTH_CATEGORY_ALIASES.forEach(function (entry) {
            entry.phrases.forEach(function (phrase) {
                var np = window.VTH_Catalog.normalize(phrase);
                var matched = q === np || q.indexOf(np) !== -1 || (np.indexOf(q) !== -1 && q.length >= 3);
                if (matched && np.length >= bestScore) {
                    bestScore = np.length;
                    bestKeys = entry.keys;
                }
            });
        });

        return bestKeys;
    },

    search: function (query) {
        var q = this.normalize(query);
        if (!q) return [];

        var categoryKeys = this.resolveCategoryKeys(query);
        if (categoryKeys && categoryKeys.length) {
            return window.VTH_CATALOG.filter(function (p) {
                return (p.menuKeys || []).some(function (k) {
                    return categoryKeys.indexOf(k) !== -1;
                });
            });
        }

        return window.VTH_CATALOG.filter(function (p) {
            var haystack = window.VTH_Catalog.normalize(
                p.name + ' ' + p.category + ' ' + (p.specs || []).join(' ') + ' ' + (p.menuKeys || []).join(' ')
            );
            return haystack.indexOf(q) !== -1;
        });
    },

    sortProducts: function (items, mode) {
        var list = items.slice();
        if (mode === 'price-asc') {
            list.sort(function (a, b) { return a.price - b.price; });
        } else if (mode === 'price-desc') {
            list.sort(function (a, b) { return b.price - a.price; });
        } else if (mode === 'name') {
            list.sort(function (a, b) { return a.name.localeCompare(b.name, 'vi'); });
        }
        return list;
    },

    renderCard: function (p) {
        var pct = this.discountPct(p.price, p.originalPrice);
        var specsHtml = '';
        if (p.specs && p.specs.length) {
            specsHtml = '<div class="product-spec-chips">' +
                p.specs.map(function (s) { return '<span class="product-spec-chip">' + s + '</span>'; }).join('') +
                '</div>';
        }

        var priceBlock = '';
        var actionBlock = '';
        if (p.contactOnly) {
            priceBlock = '<a href="lien-he.html" class="product-contact-link">Liên hệ</a>';
        } else {
            priceBlock =
                '<div class="product-prices">' +
                '<p class="product-price-sale">' + this.formatPrice(p.price) + '</p>' +
                (p.originalPrice > p.price ? '<p class="product-price"><s>' + this.formatPrice(p.originalPrice) + '</s></p>' : '') +
                '</div>';
            actionBlock = '<button type="button" class="btn-add-cart">THÊM VÀO GIỎ HÀNG</button>';
        }

        return '<article class="product-card product-card-shop' + (p.contactOnly ? ' product-card-contact' : '') + '" data-price="' + p.price + '">' +
            '<div class="product-image">' +
            (pct > 0 && !p.contactOnly ? '<span class="product-badge-pct">-' + pct + '%</span>' : '') +
            '<span class="product-logo">vitinhanhhuy.com</span>' +
            '<div class="product-img-placeholder">' + (p.icon || '📦') + '</div>' +
            specsHtml +
            '</div>' +
            '<div class="product-body">' +
            '<p class="product-category">' + p.category + '</p>' +
            '<h3 class="product-name">' + p.name + '</h3>' +
            priceBlock +
            '</div>' +
            actionBlock +
            '</article>';
    },
};
